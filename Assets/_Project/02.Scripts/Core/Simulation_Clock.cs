/// <summary>
/// 시뮬레이션 틱 번호를 세는 전역 시계입니다.
///
/// 왜 Time.frameCount를 쓰지 않는가:
/// 프레임 수는 렌더링 사정(수직동기화, 프레임 드랍, 에디터 일시정지)에 따라
/// 시뮬레이션 틱과 어긋납니다. 결정론의 기준은 '몇 번째 시뮬레이션 스텝인가'
/// 하나뿐이어야 하므로, 시뮬레이션이 직접 세는 값을 씁니다.
///
/// 이 값의 용도:
///   1) 난수 시드   : 같은 틱에는 언제나 같은 난수가 나오도록 (Simulation_Random)
///   2) 리플레이     : 명령을 "몇 번째 틱에 내렸는가"로 기록
///   3) 디버깅       : 로그에 틱 번호를 남기면 재현이 쉬워집니다
///
/// Controller가 매 FixedUpdate에서 Advance()를 호출합니다.
/// 배치 단계처럼 시뮬레이션이 멈춘 동안에는 틱도 멈춰야 하므로,
/// 실제 전투 틱이 도는 자리에서만 올려야 합니다.
/// </summary>
public static class Simulation_Clock
{
    /// <summary>현재 시뮬레이션 틱 번호입니다. 씬 시작 시 0입니다.</summary>
    public static uint tick { get; private set; }

    /// <summary>틱을 하나 진행합니다. 시뮬레이션이 실제로 도는 자리에서만 호출하십시오.</summary>
    public static void Advance()
    {
        tick++;
    }

    /// <summary>
    /// 틱을 0으로 되돌립니다. 씬 시작 시 반드시 호출해야 합니다.
    ///
    /// 정적 상태이므로 도메인 리로드를 끈 환경에서는 플레이 모드를 나가도
    /// 값이 남습니다. 초기화하지 않으면 두 번째 플레이의 난수열이
    /// 첫 번째와 달라져 '재현되지 않는' 상태가 됩니다.
    /// </summary>
    public static void Reset()
    {
        tick = 0;
    }
}

/// <summary>
/// 시뮬레이션용 결정론적 난수 시드 생성기입니다.
///
/// 왜 UnityEngine.Random을 쓰면 안 되는가:
/// 예전에는 전투 Job의 시드를 이렇게 뽑았습니다.
///
///     unit_Fight_Job.randomSeed = (uint)Random.Range(1, int.MaxValue);
///
/// UnityEngine.Random은 전역 상태를 가지며, 그 상태는 시뮬레이션 바깥
/// (이펙트, UI, 스프라이트 선택 등)에서도 소비됩니다. 즉 '누가 몇 번
/// 난수를 뽑았는가'에 따라 전투 결과가 달라집니다. 같은 명령을 같은
/// 순서로 내려도 두 번째 실행은 다른 전투가 됩니다.
///
/// 이 클래스는 시드를 '상태'가 아니라 '좌표의 함수'로 만듭니다.
///     seed = f(틱 번호, 부대 인덱스)
/// 같은 틱, 같은 부대라면 언제 어디서 호출해도 같은 값이 나옵니다.
/// 뽑는 횟수나 순서에 영향받지 않으므로 재현이 보장됩니다.
///
/// 무엇이 열리는가:
///   - 리플레이       : 명령 로그만 저장하면 전투가 그대로 재생됩니다
///   - 회귀 테스트    : 밸런스를 바꿨을 때 결과 차이가 '진짜 차이'입니다
///   - 락스텝 멀티    : 양쪽 클라이언트가 같은 전투를 계산합니다
///
/// ---------------------------------------------------------------------
/// 현재 상태: 완전한 결정론은 아직 성립하지 않습니다.
/// ---------------------------------------------------------------------
/// 9,600명 규모에서 같은 시드로 두 번 돌린 실측 결과입니다.
///
///   조치 전              : 사망 438 vs 554  (편차 26%)
///   Battle_AI를 틱 기준으로 : 600 vs 587    (편차 2.2%)
///   표적 동점/난수 분리   : 554 vs 571      (편차 3.1%)
///
/// 편차가 크게 줄었지만 0이 아닙니다. 남은 원인으로 의심되는 곳:
///
///   1) Collision_Resolve_Job의 밀어내기 누적 순서
///      각 유닛이 이웃들의 밀림을 더하는데, 그 순회가 격자 버킷 순서입니다.
///      부동소수점 덧셈은 결합법칙이 성립하지 않으므로(a+b+c != a+c+b)
///      순서가 바뀌면 위치의 최하위 비트가 달라집니다.
///      그 미세한 차이가 사거리 판정 경계에서 증폭됩니다.
///
///   2) Army_Job / Unit_Job의 워커 스레드 분배
///      IJobParallelFor의 배치 분배 자체는 결정적이지만, 위 1번처럼
///      부동소수점 누적이 끼면 결과가 갈릴 수 있습니다.
///
/// 해결 방향(미구현):
///   - 격자 순회 전에 이웃 인덱스를 정렬해 순서를 고정
///   - 또는 밀어내기 누적을 고정소수점으로 계산
///   두 방법 모두 성능 비용이 있으므로, 리플레이나 멀티플레이를 실제로
///   구현할 때 그 요구사항에 맞춰 결정하는 편이 낫습니다.
///
/// 지금 이 구조로도 얻는 것: 난수 자체는 재현되므로 '밸런스 변경의 효과'를
/// 볼 때 노이즈가 크게 줄어듭니다. 다만 완전히 같은 전투를 보장하지는 않습니다.
/// </summary>
public static class Simulation_Random
{
    /// <summary>
    /// 이 시뮬레이션 실행 전체의 기준 시드입니다.
    ///
    /// 같은 값으로 시작하면 같은 전투가 재현됩니다.
    /// 리플레이를 저장할 때 이 값을 함께 남겨야 합니다.
    /// </summary>
    public static uint masterSeed { get; private set; } = 1u;

    /// <summary>
    /// 기준 시드를 설정합니다. 씬 시작 시 한 번만 호출하십시오.
    /// 0은 Unity.Mathematics.Random이 거부하므로 1로 보정합니다.
    /// </summary>
    public static void Set_Master_Seed(uint seed)
    {
        masterSeed = seed != 0u ? seed : 1u;
    }

    /// <summary>
    /// 주어진 틱과 부대에 대한 시드를 만듭니다.
    ///
    /// 해시 방식:
    /// 두 좌표를 서로 다른 큰 홀수와 곱해 섞습니다. 곱셈 해시는 인접한
    /// 입력(틱 100과 101, 부대 3과 4)을 멀리 떨어뜨리므로, 틱이 하나
    /// 넘어갈 때마다 난수열이 통째로 바뀝니다.
    ///
    /// 마지막 xorshift 단계는 상위 비트의 편향을 하위로 퍼뜨립니다.
    /// 이 과정이 없으면 곱셈 결과의 하위 비트가 규칙적으로 반복되어,
    /// 명중 판정처럼 하위 비트를 많이 쓰는 곳에서 패턴이 드러납니다.
    /// </summary>
    /// <param name="tick">시뮬레이션 틱 번호입니다.</param>
    /// <param name="armyIndex">부대 인덱스입니다. 부대마다 다른 난수열을 갖게 합니다.</param>
    /// <returns>0이 아닌 시드입니다.</returns>
    public static uint Seed_For(uint tick, int armyIndex)
    {
        unchecked
        {
            uint seed = masterSeed;

            seed ^= (tick + 1u) * 2654435761u;          // Knuth 곱셈 해시
            seed ^= (uint)(armyIndex + 1) * 2246822519u;

            // xorshift로 비트를 고르게 섞습니다.
            seed ^= seed << 13;
            seed ^= seed >> 17;
            seed ^= seed << 5;

            // Unity.Mathematics.Random은 시드 0에서 예외를 던집니다.
            return seed != 0u ? seed : 1u;
        }
    }
}
